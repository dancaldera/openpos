interface EmojiPickerProps {
  value?: string | null
  onSelect: (emoji: string) => void
  class?: string
}

export function EmojiPicker({ value, onSelect, class: className = '' }: EmojiPickerProps) {
  const [groupKey, setGroupKey] = useState(EMOJI_GROUPS[0].key)
  const activeGroup = EMOJI_GROUPS.find((group) => group.key === groupKey) ?? EMOJI_GROUPS[0]

  return (
    <div class={`w-64 rounded-cards border border-fog-border bg-canvas shadow-sm ${className}`}>
      <div class="flex gap-0.5 border-b border-fog-border p-1">
        {EMOJI_GROUPS.map((group) => (
          <button
            key={group.key}
            type="button"
            onClick={() => setGroupKey(group.key)}
            class={`flex h-8 w-8 items-center justify-center rounded transition-colors hover:bg-chalk ${
              groupKey === group.key ? 'bg-chalk' : ''
            }`}
          >
            {group.tab}
          </button>
        ))}
      </div>
      <div class="flex max-h-44 flex-wrap gap-1 overflow-y-auto p-2">
        {activeGroup.emojis.map((emoji) => (
          <button
            key={emoji}
            type="button"
            onClick={() => onSelect(emoji)}
            class={`flex h-9 w-9 items-center justify-center rounded-cards border text-lg transition-colors hover:bg-chalk ${
              value === emoji ? 'border-void bg-chalk' : 'border-fog-border'
            }`}
          >
            {emoji}
          </button>
        ))}
      </div>
    </div>
  )
}
