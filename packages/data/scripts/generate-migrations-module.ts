import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, resolve } from 'node:path'

const packageRoot = resolve(__dirname, '..')
const migrationsDir = resolve(packageRoot, 'drizzle')
export const generatedModulePath = resolve(packageRoot, 'src/migrations.generated.js')

export function readMigrationFiles(dir = migrationsDir): Array<{ name: string; sql: string }> {
  return readdirSync(dir)
    .filter((file) => file.endsWith('.sql'))
    .sort((left, right) => left.localeCompare(right))
    .map((file) => ({ name: basename(file, '.sql'), sql: readFileSync(resolve(dir, file), 'utf-8').trim() }))
}

export function renderMigrationsModule(migrations: Array<{ name: string; sql: string }>): string {
  const entries = migrations.map(({ name, sql }) => `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`)
  return [
    '// Generated by packages/data/scripts/generate-migrations-module.ts. Do not edit by hand.',
    '// Run `pnpm -C packages/data run generate:migrations` after adding a Drizzle migration.',
    'module.exports = [',
    ...entries,
    ']',
    '',
  ].join('\n')
}

/* istanbul ignore if: production entrypoint (tests call the helpers directly). */
if (require.main === module) {
  writeFileSync(generatedModulePath, renderMigrationsModule(readMigrationFiles()))
  console.log(`Wrote ${generatedModulePath}`)
}
